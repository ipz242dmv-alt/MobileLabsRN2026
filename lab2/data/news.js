const DAY = 24 * 60 * 60 * 1000;
const START = new Date('2026-10-18T10:00:00').getTime();

export function makeNewsItem(index) {
  const id = String(index + 1);
  return {
    id,
    title: `${TOPICS[index % TOPICS.length]}`,
    category: CATEGORIES[index % CATEGORIES.length],
    date: new Date(START - index * DAY * 0.7).toISOString(),
    image: `https://picsum.photos/seed/ztu-news-${id}/600/400`,
    views: 120 + ((index * 37) % 900),
    body: PARAGRAPHS.slice(0, 2 + (index % 3)).join('\n\n'),
  };
}

export function generateNews(from, count) {
  return Array.from({ length: count }, (_, i) => makeNewsItem(from + i));
}

